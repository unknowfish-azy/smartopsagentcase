-- ============================================================
-- 哨兵任务记录「连续越界起点」
-- ============================================================
-- 需求：持续时间防抖需要一个跨轮次持久的越界起点。原实现用
-- MAX(sampled_at) 近似，但样本先落库再判定，MAX 恒等于当前轮，
-- held 恒为 0，告警永远不触发；且已有未结告警时每轮都重复告警。
-- 设计：breached_since 只在"越界且无未结告警"期间持有起点，
-- 恢复或未越界时清空；告警触发后清空，由未结告警存在性接管去重。
-- 幂等：由 SentinelConfig 先探测列是否存在再执行。

ALTER TABLE sentinel_task ADD COLUMN breached_since TIMESTAMP NULL;
