-- PERF-01：哨兵调度的排队与慢目标观测
-- ============================================================
-- last_duration_ms 记录"上一次采集实测耗时"（由 System.nanoTime 测得），
-- 用于下一轮判断该目标是否为慢目标：慢目标走独立车道，最多占少数槽位，
-- 不会把整轮的到期延迟拉大。
--
-- 只记录实测值，不写入估算值；采集失败时记录的是失败前已消耗的时间。

ALTER TABLE sentinel_task ADD COLUMN last_duration_ms INT NULL;
