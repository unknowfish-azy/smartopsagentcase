-- AI 运维决策闭环：分析 → 记忆 → 决策 → 复盘 → 学习回写
CREATE TABLE IF NOT EXISTS agent_decision_loop (
    id VARCHAR(32) PRIMARY KEY,
    user_id BIGINT NOT NULL,
    incident_key VARCHAR(255) NOT NULL,
    title VARCHAR(255) NOT NULL,
    source_type VARCHAR(32) NOT NULL DEFAULT 'MANUAL',
    source_ref VARCHAR(128),
    stage VARCHAR(32) NOT NULL DEFAULT 'ANALYZE',
    severity VARCHAR(32) NOT NULL DEFAULT 'MEDIUM',
    symptom TEXT,
    analysis TEXT,
    evidence_json TEXT,
    memory_refs TEXT,
    recommendation TEXT,
    decision TEXT,
    decision_basis TEXT,
    requires_human BOOLEAN NOT NULL DEFAULT FALSE,
    outcome VARCHAR(32),
    lesson TEXT,
    learned_memory_ids TEXT,
    learned_count INT NOT NULL DEFAULT 0,
    confidence DOUBLE NOT NULL DEFAULT 0.5,
    reviewed_at TIMESTAMP NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX idx_agent_decision_loop_user (user_id, updated_at),
    INDEX idx_agent_decision_loop_source (source_type, source_ref)
);
