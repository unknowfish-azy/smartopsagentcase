-- ============================================================
-- 哨兵任务的「资产分组」启停
-- ============================================================
-- 需求：资产分组启停。原实现只能单个任务启停，多台机器要逐个点。
--
-- 设计取舍：不在既有 server 表上引入新的分组实体，而是在哨兵任务上加一个
-- group_label（自由文本，如 web-prod / db-core）。理由：
--   1. 哨兵任务本身已经有"目标主机"语义，再建一层实体只增加同步负担；
--   2. 分组是运维标签而不是基础设施事实，改了不该影响 server 记录；
--   3. 空值 = 未分组，与既有数据天然兼容。
-- 幂等：由 Java 侧先探测列是否存在再执行。

ALTER TABLE sentinel_task ADD COLUMN group_label VARCHAR(64) NULL;
